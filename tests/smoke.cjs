// Requires Playwright and a running static server. Uses isolated browser contexts.
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const base = process.env.GROWPWE_TEST_URL || 'http://127.0.0.1:8080';
(async () => {
  const browser = await chromium.launch({executablePath: process.env.GROWPWE_CHROMIUM || '/usr/bin/chromium', args:['--no-sandbox'], env:{...process.env,XDG_CACHE_HOME:'/tmp/growpwe-test-cache',XDG_CONFIG_HOME:'/tmp/growpwe-test-config'}});
  try {
    const context = await browser.newContext({viewport:{width:1440,height:1100}});
    const errors = []; context.on('page', page=>page.on('pageerror',error=>errors.push(error.message)));
    const page = await context.newPage(); await page.goto(base);
    assert.equal(await page.locator('#total').innerText(),'04');
    await page.getByRole('button',{name:'Criar lote'}).click();
    await page.locator('#field-lotName').fill('Estudo <img src=x onerror=alert(1)>');
    await page.locator('#field-prefix').fill('LAB');
    await page.locator('#field-planned').fill('2');await page.locator('#field-started').fill('3');
    await page.getByRole('button',{name:'Continuar',exact:true}).click();
    assert.match(await page.locator('#form-error').innerText(),/menor ou igual/);
    await page.locator('#field-planned').fill('5');
    await page.locator('#field-species').fill('Espécie declarada');
    await page.locator('#field-cultivar').fill('Cultivar demonstrativa');
    await page.locator('#field-plantType').selectOption('Fotoperiódica');
    await page.locator('#field-phase').selectOption('Vegetação');
    await page.getByRole('button',{name:'Continuar',exact:true}).click();
    await page.locator('#field-medium').selectOption('Fibra de coco');
    await page.locator('#field-containerShape').selectOption('Quadrado');
    await page.locator('#field-containerVolume').fill('10');
    await page.getByRole('button',{name:'Continuar',exact:true}).click();
    assert.match(await page.locator('#review-summary').innerText(),/5 unidades planejadas; 3 espécimes/);
    assert.equal(await page.locator('#review img').count(),0);
    assert.equal(await page.locator('#total').innerText(),'04','review must not persist');
    await page.getByRole('button',{name:'Voltar',exact:true}).click();
    await page.locator('#field-containerShape').selectOption('Circular');
    await page.getByRole('button',{name:'Continuar',exact:true}).click();
    assert.match(await page.locator('#review-fields').innerText(),/Circular/);
    await page.getByRole('button',{name:'Confirmar e criar lote'}).click();
    const data = await page.evaluate(()=>JSON.parse(localStorage.getItem('growpwe-v1')));
    assert.equal(data.specimens.length,7);assert.equal(data.lots.length,1);
    assert.equal(data.lots[0].data.containerShape,'Circular');assert.equal(data.lots[0].data.nominalPower,null);
    const added = data.specimens.filter(x=>x.lotId);assert.equal(new Set(added.map(x=>x.id)).size,3);
    assert.equal(new Set(added.map(x=>x.name)).size,3);assert.match(added[0].name,/^LAB-[A-F0-9]{12}-001$/);
    await page.reload();assert.equal(await page.locator('#total').innerText(),'07');
    const stable = await page.evaluate(()=>JSON.parse(localStorage.getItem('growpwe-v1')).specimens.map(s=>s.id));
    assert.deepEqual(stable,data.specimens.map(s=>s.id));
    await page.locator('[data-page="specimens"]').click();
    for(const specimen of added.slice(0,2)) await page.locator(`[data-specimen-id="${specimen.id}"]`).check();
    await page.getByRole('button',{name:'Preparar etiquetas'}).click();
    await page.locator('#label-width').fill('60');await page.locator('#label-height').fill('40');
    const [labels] = await Promise.all([context.waitForEvent('page'),page.getByRole('button',{name:'Abrir prévia de impressão'}).click()]);
    await labels.waitForSelector('.label');assert.equal(await labels.locator('.label').count(),2);assert.equal(await labels.locator('.sheet').count(),2);
    assert.equal(await labels.locator('img').count(),0);assert.match(await labels.locator('.uuid').first().innerText(),new RegExp(added[0].id));
    await labels.emulateMedia({media:'print'});
    const rollPdf = await labels.pdf({preferCSSPageSize:true,path:'/tmp/growpwe-labels-roll.pdf'});
    assert(rollPdf.length>1000);
    const sizes = await labels.locator('.label').evaluateAll(elements=>elements.map(el=>({w:el.getBoundingClientRect().width,h:el.getBoundingClientRect().height,overflow:el.scrollHeight>el.clientHeight})));
    assert(sizes.every(s=>Math.abs(s.w-60*96/25.4)<1&&Math.abs(s.h-40*96/25.4)<1&&!s.overflow));
    await labels.reload();await labels.waitForSelector('.label');assert.equal(await labels.locator('.label').count(),2,'print preview must survive reload');
    await page.getByRole('button',{name:'Preparar etiquetas'}).click();await page.locator('#label-layout').selectOption('a4');
    const [a4] = await Promise.all([context.waitForEvent('page'),page.getByRole('button',{name:'Abrir prévia de impressão'}).click()]);
    await a4.waitForSelector('.label');assert.equal(await a4.locator('.sheet.a4').count(),1);
    await a4.pdf({preferCSSPageSize:true,path:'/tmp/growpwe-labels-a4.pdf'});
    // Verify actual multi-page A4 layout and minimum-size label readability.
    const boundary=await context.newPage();await boundary.goto(base);
    const jobs=await boundary.evaluate(()=>{
      const records=Array.from({length:19},()=>({id:crypto.randomUUID(),code:'PREFIX08-ABCDEF123456-999',lot:'Nome longo de lote '.repeat(12),cultivar:'Nome longo de cultivar '.repeat(12),startDate:'2026-10-14'}));
      const a4id=crypto.randomUUID(),smallid=crypto.randomUUID();
      sessionStorage.setItem('growpwe-print-'+a4id,JSON.stringify({version:1,width:60,height:40,layout:'a4',records}));
      sessionStorage.setItem('growpwe-print-'+smallid,JSON.stringify({version:1,width:40,height:30,layout:'roll',records:records.slice(0,1)}));
      return {a4id,smallid};
    });
    await boundary.goto(base+'/labels.html?job='+jobs.a4id);await boundary.waitForSelector('.label');
    assert.equal(await boundary.locator('.label').count(),19);assert.equal(await boundary.locator('.sheet').count(),2);
    await boundary.pdf({preferCSSPageSize:true,path:'/tmp/growpwe-labels-multipage.pdf'});
    await boundary.goto(base+'/labels.html?job='+jobs.smallid);await boundary.waitForSelector('.label');
    await boundary.emulateMedia({media:'print'});
    assert.equal(await boundary.locator('.label').evaluate(el=>el.scrollHeight>el.clientHeight),false,'minimum-size label clips content');
    await boundary.pdf({preferCSSPageSize:true,path:'/tmp/growpwe-labels-small.pdf'});
    await boundary.close();
    // Individual reprint must use the same UUID, not issue a new one.
    await page.getByRole('button',{name:'Detalhes de '+added[0].name,exact:true}).click();
    await page.getByRole('button',{name:'Etiqueta deste espécime'}).click();
    assert.match(await page.locator('#labels-summary').innerText(),/^1 etiqueta,/);
    await page.getByRole('button',{name:'Cancelar',exact:true}).click();
    const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Exportar registros'}).click();
    const download=await downloadPromise;await download.saveAs('/tmp/growpwe-export-test.json');
    const exported=JSON.parse(require('node:fs').readFileSync('/tmp/growpwe-export-test.json','utf8'));assert.equal(exported.specimens.length,7);
    await page.getByRole('button',{name:'Criar lote'}).click();await page.locator('#field-lotName').fill('Planejamento');await page.locator('#field-started').fill('0');
    await page.getByRole('button',{name:'Continuar',exact:true}).click();await page.getByRole('button',{name:'Continuar',exact:true}).click();await page.getByRole('button',{name:'Confirmar e criar lote'}).click();
    assert.equal(await page.locator('#specimen-list .specimen-item').count(),7,'planned units must not become specimens');
    await page.locator('[data-page="overview"]').click();await page.screenshot({path:'/tmp/growpwe-lotes.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});await page.getByRole('button',{name:'Criar lote'}).click();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    assert.equal(await page.locator('#create-dialog').evaluate(el=>el.scrollWidth>el.clientWidth),false);
    await page.locator('#cancel').click();
    assert.equal(errors.length,0,errors.join('; '));
    const legacyContext=await browser.newContext();const legacyPage=await legacyContext.newPage();
    await legacyPage.addInitScript(()=>{if(!localStorage.getItem('growpwe-v1'))localStorage.setItem('growpwe-demo',JSON.stringify([{name:'LEGADO-01',phase:'Floração'}]))});
    await legacyPage.goto(base);assert.equal(await legacyPage.locator('#total').innerText(),'01');
    assert.equal(await legacyPage.evaluate(()=>JSON.parse(localStorage.getItem('growpwe-v1')).specimens[0].name),'LEGADO-01');
    const legacyId=await legacyPage.evaluate(()=>JSON.parse(localStorage.getItem('growpwe-v1')).specimens[0].id);await legacyPage.reload();
    assert.equal(await legacyPage.evaluate(()=>JSON.parse(localStorage.getItem('growpwe-v1')).specimens[0].id),legacyId);
    const corruptContext=await browser.newContext();const corrupt=await corruptContext.newPage();await corrupt.addInitScript(()=>localStorage.setItem('growpwe-v1','not-json'));
    await corrupt.goto(base);assert.equal(await corrupt.evaluate(()=>localStorage.getItem('growpwe-v1')),'not-json');
    assert.match(await corrupt.locator('#toast').innerText(),/inválidos/);
    await context.close();await legacyContext.close();await corruptContext.close();
    console.log('PASS: quantity validation, review/edit, batch creation, stable IDs, persistence, safe text, selected roll/A4 labels, PDF generation, individual reprint, export, zero-start planning, mobile, legacy migration, corrupt-data preservation.');
  } finally {await browser.close()}
})().catch(error=>{console.error(error);process.exit(1)});
